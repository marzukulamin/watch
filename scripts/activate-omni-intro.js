import fs from 'node:fs/promises';
import { db, close } from '../server/db.js';
const media = new URL('../public/media/intro/', import.meta.url);
const reportPath = new URL('../docs/reference/omni-v2-production.json', import.meta.url);
const report = JSON.parse(await fs.readFile(reportPath, 'utf8'));
for (const name of [
  'verse-watch-outlet-desktop.v2.mp4',
  'verse-watch-outlet-mobile.v2.mp4',
  'verse-full-intro.v2.mp4',
]) {
  if ((await fs.stat(new URL(name, media))).size < 1000)
    throw Error(`Missing production asset ${name}`);
}
report.visually_inspected = true;
report.activated = true;
report.activated_at = new Date().toISOString();
report.review =
  'Inspected full master/contact sheet, portrait crop, full-resolution branding reveal and original shot continuity. Website uses local silent story footage with exact HTML source logo/wordmark. Full export includes exact composited opening/finale branding.';
await fs.writeFile(reportPath, JSON.stringify(report, null, 2) + '\n');
await fs.writeFile(
  new URL('manifest.json', media),
  JSON.stringify(
    {
      mode: 'omni-video',
      version: 'watch-outlet-v2',
      inspected: true,
      desktop: '/media/intro/verse-watch-outlet-desktop.v2.mp4',
      mobile: '/media/intro/verse-watch-outlet-mobile.v2.mp4',
      poster: '/media/intro/verse-outlet-poster.v2.webp',
      full_export: '/media/intro/verse-full-intro.v2.mp4',
      duration_seconds: 18,
      logo_reveal_seconds: 14.5,
      note: 'Original watch and architectural brand concept, generated by Gemini Omni Flash. Official source logo and precise HTML lettering appear after the doors open.',
    },
    null,
    2,
  ) + '\n',
);
for (const slug of ['privacy', 'cookies']) {
  const row = await db.get('SELECT * FROM policies WHERE slug=?', [slug]);
  if (!row) continue;
  const sections = JSON.parse(row.sections_json);
  const section = sections.find((s) => s.heading === 'Cinematic introduction');
  if (section)
    section.body = section.body.replace(
      'It contains only 1',
      'It contains only the presentation version watch-outlet-v2',
    );
  await db.run('UPDATE policies SET sections_json=?,version=?,updated_at=? WHERE id=?', [
    JSON.stringify(sections),
    '2026-10-09.3',
    new Date().toISOString(),
    row.id,
  ]);
}
await close();
console.log('Activated inspected Omni story. No Cloud requests are made by visitors.');
